"""Extract state machines and flag transitions the code can reach but not finish.

The audit procedure is: write one file of states, invariants, and transition
tables; keep a finding only when a path in the code reaches an invalid
transition (a retry that never ends, a lock that stays held); fix those with
tests; regenerate the file.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from tree_sitter import Node

from vibeguard.models import Finding, Language, SourceFile
from vibeguard.ts_parse import node_text, parser_for, walk_tree

_CODE = frozenset({Language.PYTHON, Language.TYPESCRIPT, Language.TSX, Language.JAVASCRIPT})


@dataclass
class Transition:
    source: str
    event: str
    target: str
    line: int


@dataclass
class Machine:
    name: str
    file: str
    line: int
    kind: str
    states: list[str] = field(default_factory=list)
    transitions: list[Transition] = field(default_factory=list)
    invariant: str = ""


def extract_machines(files: list[SourceFile]) -> list[Machine]:
    """Enums, match/switch arms, retry loops, and locks. Order is file then line."""
    machines: list[Machine] = []
    for source in files:
        if source.language not in _CODE:
            continue
        root = _root(source)
        if root is None:
            continue
        if source.language == Language.PYTHON:
            machines.extend(_python_machines(source, root))
        else:
            machines.extend(_script_machines(source, root))
    machines.sort(key=lambda machine: (machine.file, machine.line, machine.name))
    return machines


def detect_state_bugs(source: SourceFile) -> list[Finding]:
    """Flag a retry with no terminal failure, or a lock acquire with no release."""
    if source.language not in _CODE:
        return []
    root = _root(source)
    if root is None:
        return []
    if source.language == Language.PYTHON:
        return _python_bugs(source, root)
    return _script_bugs(source, root)


def render_states(machines: list[Machine], findings: list[Finding]) -> str:
    """One markdown file: tables first, then the transitions the code can reach."""
    lines = [
        "# State machines",
        "",
        "Generated by `vibeguard states`. Re-run it after a fix so this file matches the code.",
        "A finding below is a transition the function can enter and not finish.",
        "",
    ]
    if not machines and not findings:
        lines.append("No explicit state machine, retry loop, or lock acquire was found.")
        lines.append("")
        return "\n".join(lines)
    for machine in machines:
        lines.extend(_render_machine(machine))
    lines.append("## Confirmed invalid transitions")
    lines.append("")
    state_findings = [finding for finding in findings if finding.rule_id.startswith("D8.")]
    if not state_findings:
        lines.append("None. Every extracted retry ends, and every extracted lock is released.")
        lines.append("")
        return "\n".join(lines)
    lines.append("| Severity | Rule | Location | Evidence |")
    lines.append("| --- | --- | --- | --- |")
    for finding in state_findings:
        evidence = (finding.snippet or finding.message).replace("|", "\\|")
        lines.append(
            f"| {finding.severity.value} | `{finding.rule_id}` | `{finding.file}:{finding.line}` | {evidence} |"
        )
    lines.append("")
    return "\n".join(lines)


def _render_machine(machine: Machine) -> list[str]:
    states = ", ".join(f"`{state}`" for state in machine.states) or "(none named)"
    lines = [
        f"## {machine.name}",
        "",
        f"`{machine.file}:{machine.line}` · {machine.kind}",
        "",
        f"Invariant: {machine.invariant}",
        "",
        f"States: {states}",
        "",
        "| From | Event | To | Line |",
        "| --- | --- | --- | --- |",
    ]
    if machine.transitions:
        for edge in machine.transitions:
            lines.append(
                f"| `{edge.source}` | {edge.event} | `{edge.target}` | {edge.line} |"
            )
    else:
        lines.append("| — | — | — | — |")
    lines.append("")
    return lines


def _root(source: SourceFile) -> Node | None:
    parser = parser_for(source)
    if parser is None or not source.text.strip():
        return None
    return parser.parse(source.text.encode("utf-8")).root_node


def _python_machines(source: SourceFile, root: Node) -> list[Machine]:
    machines: list[Machine] = []
    for node in walk_tree(root):
        if node.type == "class_definition" and _is_enum(node):
            machines.append(_enum_machine(source, node))
        elif node.type == "function_definition":
            machines.extend(_python_function_machines(source, node))
    return machines


def _script_machines(source: SourceFile, root: Node) -> list[Machine]:
    machines: list[Machine] = []
    for node in walk_tree(root):
        if node.type in {"type_alias_declaration", "type_alias"}:
            machine = _union_machine(source, node)
            if machine is not None:
                machines.append(machine)
        elif node.type in {"function_declaration", "method_definition", "arrow_function"}:
            machines.extend(_script_function_machines(source, node))
    return machines


def _python_bugs(source: SourceFile, root: Node) -> list[Finding]:
    findings: list[Finding] = []
    for node in walk_tree(root):
        if node.type != "function_definition":
            continue
        findings.extend(_unbounded_retries(source, node))
        findings.extend(_retry_fallthrough(source, node))
        findings.extend(_held_locks(source, node))
    return findings


def _script_bugs(source: SourceFile, root: Node) -> list[Finding]:
    findings: list[Finding] = []
    for node in walk_tree(root):
        if node.type not in {"function_declaration", "method_definition", "arrow_function"}:
            continue
        findings.extend(_unbounded_retries(source, node))
    return findings


def _python_function_machines(source: SourceFile, fn: Node) -> list[Machine]:
    name = _fn_name(fn)
    machines: list[Machine] = []
    for node in walk_tree(fn):
        if node.type == "while_statement" and _is_true_loop(node):
            machines.append(_retry_machine(source, name, node, _except_can_exit(node, "except_clause")))
        elif node.type == "for_statement" and _is_bounded_retry(node):
            machines.append(_retry_machine(source, name, node, _for_retry_ends(node, fn)))
        elif _is_gather(node):
            machines.append(_gather_machine(source, name, node))
        elif node.type == "with_statement" and _acquires_in(node):
            machines.append(_lock_machine(source, name, node, released=True))
        elif node.type == "call" and _is_acquire_call(node) and not _inside(node, "with_statement"):
            machines.append(_lock_machine(source, name, node, released=_finally_releases(fn)))
    return machines


def _script_function_machines(source: SourceFile, fn: Node) -> list[Machine]:
    name = _fn_name(fn)
    machines: list[Machine] = []
    for node in walk_tree(fn):
        if node.type == "while_statement" and _is_true_loop(node):
            machines.append(_retry_machine(source, name, node, _except_can_exit(node, "catch_clause")))
        elif node.type == "switch_statement":
            machine = _switch_machine(source, name, node)
            if machine is not None:
                machines.append(machine)
    return machines


def _enum_machine(source: SourceFile, node: Node) -> Machine:
    name_node = node.child_by_field_name("name")
    name = node_text(name_node) if name_node is not None else "Enum"
    states: list[str] = []
    body = node.child_by_field_name("body")
    if body is not None:
        for child in body.named_children:
            target = child.named_children[0] if child.type == "expression_statement" and child.named_children else child
            if target.type == "assignment":
                left = target.child_by_field_name("left")
                if left is not None and left.type == "identifier":
                    states.append(node_text(left))
    return Machine(
        name=name,
        file=source.path,
        line=node.start_point[0] + 1,
        kind="enum",
        states=states,
        transitions=[
            Transition("caller", f"set {state}", state, node.start_point[0] + 1) for state in states
        ],
        invariant=f"A {name} value is one of the members listed here.",
    )


def _union_machine(source: SourceFile, node: Node) -> Machine | None:
    name_node = node.child_by_field_name("name")
    value = node.child_by_field_name("value")
    if name_node is None or value is None or value.type != "union_type":
        return None
    states = [_literal(child) for child in value.named_children]
    states = [state for state in states if state]
    if len(states) < 2:
        return None
    name = node_text(name_node)
    return Machine(
        name=name,
        file=source.path,
        line=node.start_point[0] + 1,
        kind="union",
        states=states,
        transitions=[Transition("caller", f"set {state}", state, node.start_point[0] + 1) for state in states],
        invariant=f"A {name} value is one of the literals listed here.",
    )


def _switch_machine(source: SourceFile, fn_name: str, node: Node) -> Machine | None:
    subject = node.child_by_field_name("value") or node.child_by_field_name("condition")
    subject_text = node_text(subject) if subject is not None else "value"
    edges: list[Transition] = []
    for case in node.named_children:
        if case.type not in {"switch_case", "switch_default"}:
            continue
        label = case.child_by_field_name("value")
        target = node_text(label) if label is not None else "default"
        edges.append(Transition(subject_text, "case", target.strip("'\""), case.start_point[0] + 1))
    if not edges:
        return None
    return Machine(
        name=f"{fn_name} switch",
        file=source.path,
        line=node.start_point[0] + 1,
        kind="switch",
        states=[edge.target for edge in edges],
        transitions=edges,
        invariant=f"Each {subject_text} arm ends in that case's body.",
    )


def _retry_machine(source: SourceFile, fn_name: str, node: Node, can_exit: bool) -> Machine:
    line = node.start_point[0] + 1
    edges = [
        Transition("start", "attempt", "in-flight", line),
        Transition("in-flight", "return", "done", line),
        Transition("in-flight", "catch", "retry-wait" if not can_exit else "failed-or-retry", line),
    ]
    if can_exit:
        edges.append(Transition("failed-or-retry", "raise, return, or break", "terminal", line))
    return Machine(
        name=f"{fn_name} retry",
        file=source.path,
        line=line,
        kind="retry",
        states=["start", "in-flight", "retry-wait", "done", "terminal"],
        transitions=edges,
        invariant=(
            "A caught failure reaches raise, return, or break."
            if can_exit
            else "The catch path does not reach a terminal state."
        ),
    )


def _lock_machine(source: SourceFile, fn_name: str, node: Node, released: bool) -> Machine:
    line = node.start_point[0] + 1
    edges = [Transition("free", "acquire", "held", line)]
    if released:
        edges.append(Transition("held", "release or with-block exit", "free", line))
    return Machine(
        name=f"{fn_name} lock",
        file=source.path,
        line=line,
        kind="lock",
        states=["free", "held"],
        transitions=edges,
        invariant="After acquire, every exit releases the lock." if released else "Acquire has no release on the exit path.",
    )


def _retry_fallthrough(source: SourceFile, fn: Node) -> list[Finding]:
    findings: list[Finding] = []
    for node in walk_tree(fn):
        if node.type != "for_statement" or not _is_bounded_retry(node):
            continue
        if _except_can_exit(node, "except_clause"):
            continue
        if _path_can_finish_after(node, fn):
            continue
        findings.append(
            _bug(
                "D8.retry_falls_through",
                source,
                node,
                "Every caught attempt fails and the loop then ends without raise or return, so the caller can see success.",
            )
        )
    return findings


def _unbounded_retries(source: SourceFile, fn: Node) -> list[Finding]:
    findings: list[Finding] = []
    for node in walk_tree(fn):
        if node.type != "while_statement" or not _is_true_loop(node):
            continue
        if not _has_handler(node):
            continue
        handler = "except_clause" if source.language == Language.PYTHON else "catch_clause"
        if _except_can_exit(node, handler):
            continue
        findings.append(
            _bug(
                "D8.unbounded_retry",
                source,
                node,
                "Retry loop catches failures and never raises, returns, or breaks, so a failed attempt cannot reach a terminal state.",
            )
        )
    return findings


def _held_locks(source: SourceFile, fn: Node) -> list[Finding]:
    if _finally_releases(fn):
        return []
    findings: list[Finding] = []
    for node in walk_tree(fn):
        if node.type != "call" or not _is_acquire_call(node):
            continue
        if _inside(node, "with_statement"):
            continue
        findings.append(
            _bug(
                "D8.lock_not_released",
                source,
                node,
                "Lock is acquired without a with-statement or a finally that releases it, so an error leaves it held.",
            )
        )
    return findings


def _bug(rule_id: str, source: SourceFile, node: Node, message: str) -> Finding:
    line = node.start_point[0] + 1
    return Finding(
        rule_id=rule_id,
        file=source.path,
        line=line,
        message=message,
        snippet=node_text(node).splitlines()[0][:160],
    )


def _is_enum(node: Node) -> bool:
    supers = node.child_by_field_name("superclasses")
    if supers is None:
        return False
    return "Enum" in node_text(supers)


def _is_bounded_retry(node: Node) -> bool:
    """A for-range loop whose body handles an exception: a bounded retry."""
    if not _contains_type(node, "try_statement"):
        return False
    right = node.child_by_field_name("right")
    if right is None or right.type != "call":
        return False
    fn = right.child_by_field_name("function")
    return fn is not None and node_text(fn) == "range"


def _for_retry_ends(loop: Node, fn: Node) -> bool:
    return _except_can_exit(loop, "except_clause") or _path_can_finish_after(loop, fn)


def _path_can_finish_after(loop: Node, fn: Node) -> bool:
    node = loop
    while node is not None and node != fn:
        parent = node.parent
        if parent is None:
            return False
        seen = False
        for child in parent.named_children:
            if child == node:
                seen = True
                continue
            if seen and _contains_exit(child):
                return True
        node = parent
    return False


def _is_gather(node: Node) -> bool:
    if node.type != "call":
        return False
    fn = node.child_by_field_name("function")
    if fn is None or fn.type != "attribute":
        return False
    attr = fn.child_by_field_name("attribute")
    return attr is not None and node_text(attr) == "gather"


def _gather_machine(source: SourceFile, fn_name: str, node: Node) -> Machine:
    line = node.start_point[0] + 1
    returns = "return_exceptions" in node_text(node)
    return Machine(
        name=f"{fn_name} gather",
        file=source.path,
        line=line,
        kind="concurrency",
        states=["spawned", "joined", "failed"],
        transitions=[
            Transition("caller", "await gather", "joined" if returns else "joined-or-cancel", line),
            Transition("spawned", "task raises", "failed" if returns else "cancel siblings", line),
        ],
        invariant=(
            "A failing task is a result value, not a cancellation of the others."
            if returns
            else "A failing task cancels the tasks still running, unless the caller handles that."
        ),
    )


def _is_true_loop(node: Node) -> bool:
    condition = node.child_by_field_name("condition")
    if condition is None:
        return False
    text = node_text(condition).strip()
    return text in {"True", "true", "1"}


def _has_handler(node: Node) -> bool:
    return any(child.type in {"try_statement", "try"} or _contains_type(child, "try_statement") for child in walk_tree(node))


def _except_can_exit(loop: Node, handler_type: str) -> bool:
    handlers = [node for node in walk_tree(loop) if node.type == handler_type]
    if not handlers:
        return True
    return all(_contains_exit(handler) for handler in handlers)


def _contains_exit(node: Node) -> bool:
    exits = {"break_statement", "return_statement", "raise_statement", "throw_statement"}
    return any(child.type in exits for child in walk_tree(node))


def _contains_type(node: Node, node_type: str) -> bool:
    return any(child.type == node_type for child in walk_tree(node))


def _finally_releases(fn: Node) -> bool:
    for node in walk_tree(fn):
        if node.type != "finally_clause":
            continue
        text = node_text(node)
        if ".release(" in text or "LOCK_UN" in text or ".unlock(" in text:
            return True
    return False


def _acquires_in(node: Node) -> bool:
    return any(_is_acquire_call(child) for child in walk_tree(node) if child.type == "call")


def _is_acquire_call(node: Node) -> bool:
    fn = node.child_by_field_name("function")
    if fn is None:
        return False
    if fn.type == "attribute":
        attr = fn.child_by_field_name("attribute")
        return attr is not None and node_text(attr) in {"acquire", "lock"}
    return False


def _inside(node: Node, ancestor_type: str) -> bool:
    parent = node.parent
    while parent is not None:
        if parent.type == ancestor_type:
            return True
        parent = parent.parent
    return False


def _fn_name(node: Node) -> str:
    name = node.child_by_field_name("name")
    if name is not None:
        return node_text(name)
    return "anonymous"


def _literal(node: Node) -> str:
    if node.type in {"literal_type", "literal"}:
        inner = node.named_children[0] if node.named_children else node
        return node_text(inner).strip("'\"")
    if node.type == "string":
        return node_text(node).strip("'\"")
    return ""
